export const departments = DEPARTMENTS;

export function getDepartmentById(deptId) {
  if (!deptId) return DEPARTMENTS[0];
  const query = String(deptId).toLowerCase().trim();
  return (
    DEPARTMENTS.find(
      d =>
        d.id.toLowerCase() === query ||
        d.tokenPrefix.toLowerCase() === query ||
        (d.aliases && d.aliases.some(a => a.toLowerCase() === query))
    ) || DEPARTMENTS[0]
  );
}

